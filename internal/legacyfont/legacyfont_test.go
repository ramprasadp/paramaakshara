func TestReorder(t *testing.T) {
	u := func(kind, text string) unit { return unit{kind: kind, text: text} }
	for _, c := range []struct {
		name string
		in   []unit
		want string
	}{
		{"pre sign after a conjunct", []unit{u(Pre, "ि"), u(Half, "स्"), u(Consonant, "थ")}, "स्थि"},
		{"reph before its cluster", []unit{u(Pre, "ि"), u(Consonant, "द"), u(Reph, "र्")}, "र्दि"},
		{"visarga before the accent", []unit{u(Consonant, "म"), u(Accent, "॑"), u(Modifier, "ः")}, "मः॑"},
		{"accent after a space", []unit{u(Modifier, "ं"), u(Space, " "), u(Accent, "॒"), u(Consonant, "न")}, "ं॒ न"},
		{"accent after a danda stays", []unit{u(Punct, "।"), u(Space, " "), u(Accent, "॒")}, "। ॒"},
		{"stem after an accent", []unit{u(Pre, "ि"), u(Half, "व्"), u(Accent, "॒"), u(Stem, "")}, "वि॒"},
		{"sign before the accent", []unit{u(Consonant, "ष"), u(Accent, "॒"), u(Sign, "ा")}, "षा॒"},
		{"pre sign after a subjoined ra", []unit{u(Pre, "ि"), u(Consonant, "प"), u(Subjoined, "्र")}, "प्रि"},
		{"compose across an accent", []unit{u(Consonant, "त"), u(Sign, "ा"), u(Accent, "॒"), u(Sign, "े")}, "तो॒"},
	} {
		var sb strings.Builder
		for _, x := range reorder(c.in, map[[2]string]string{{"ा", "े"}: "ो"}) {
			sb.WriteString(x.text)
		}
		if got := sb.String(); got != c.want {
			t.Errorf("%s: got %q, want %q", c.name, got, c.want)
		}
	}
}

