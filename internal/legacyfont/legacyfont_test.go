package legacyfont

import (
	"encoding/hex"
	"strings"
	"testing"
)

func table(t *testing.T, font string) *Table {
	t.Helper()
	tables, err := Tables()
	if err != nil {
		t.Fatal(err)
	}
	tb := tables[font]
	if tb == nil {
		t.Fatalf("no table for %s", font)
	}
	return tb
}

func codes(t *testing.T, h string) []byte {
	t.Helper()
	b, err := hex.DecodeString(strings.ReplaceAll(h, " ", ""))
	if err != nil {
		t.Fatal(err)
	}
	return b
}

