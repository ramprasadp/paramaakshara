"""Generates frontend/src/conversion/script-tables.ts.

Devanagari, Kannada and Tamil share the ISCII-derived layout, so most
characters map by a fixed offset. A pair is kept only if both characters
exist and their Unicode names match (allowing for Devanagari E/O being
the long vowels EE/OO of the Dravidian scripts). Run with:

    python3 -I tools/gen-script-tables.py > frontend/src/conversion/script-tables.ts
"""
import unicodedata as u


def name(c):
    try:
        return u.name(chr(c))
    except ValueError:
        return None


def same(dev, other):
    if dev == other:
        return True
    long_forms = {"LETTER E": "LETTER EE", "LETTER O": "LETTER OO",
                  "VOWEL SIGN E": "VOWEL SIGN EE", "VOWEL SIGN O": "VOWEL SIGN OO"}
    if long_forms.get(dev) == other:
        return True
    return dev.startswith(("LETTER SHORT ", "VOWEL SIGN SHORT ")) and dev.replace("SHORT ", "") == other


def pairs(offset, script):
    out = []
    for c in range(0x0900, 0x0980):
        d, t = name(c), name(c + offset)
        if d and t and same(d.replace("DEVANAGARI ", "", 1), t.replace(script + " ", "", 1)):
            out.append((c, c + offset, d))
    return out


print(f"""// SPDX-License-Identifier: GPL-3.0-or-later

// Generated by tools/gen-script-tables.py from the Unicode Character
// Database {u.unidata_version}. Do not edit by hand.
//
// Devanagari code point → same character in Kannada / Tamil.
""")
for var, offset, script in [("KANNADA", 0x380, "KANNADA"), ("TAMIL", 0x280, "TAMIL")]:
    print(f"export const {var}: ReadonlyMap<number, number> = new Map([")
    for d, t, n in pairs(offset, script):
        print(f"  [0x{d:04X}, 0x{t:04X}], // {n}")
    print("]);\n")
